import { writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Table } from '../resolution/addresses';

// WHERE EACH BOOK STANDS. Addressing only: every route reaches its book through the one door the
// assembly wrote, so a page is loaded the same way whoever asks for it.
//
// AND NO SHELF. Every address a page carries is written into its source by the reference transform,
// so nothing at runtime looks a book up by name — Doug, 2026-09-19: "There should not be anymore
// dynamic link generation."
//
// THE TEXT OF IT, WITHOUT WRITING IT ANYWHERE, so a dev server can serve this module with no file
// for it on disk. The batch below still writes one, because a publish bundles files.
export const assembled = (table: Table): string => {
    const lines = [
        `// GENERATED by assembly/routes.ts on every build — never edited. Where each book of the library stands.`,
        `import { books } from './books';`,
        ``,
        `export const routes = [`,
        ...table.routes.map(route =>
            `    { name: ${JSON.stringify(route.name)}, folder: ${JSON.stringify(route.folder)}, address: ${JSON.stringify(route.address)}, load: books[${JSON.stringify(route.folder)}] },`),
        `];`,
        ``,
        `export const root = ${table.root ? `routes[${table.routes.indexOf(table.root)}]` : 'undefined'};`,
        ``,
    ];

    return lines.join('\n');
};

export const routes = (binding: string, table: Table): string => {
    const at = join(binding, 'application', 'routes.ts');
    writeFileSync(at, assembled(table), 'utf8');

    return relative(join(binding, '..'), at).split(sep).join('/');
};
