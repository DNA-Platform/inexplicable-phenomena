import { writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Configuration } from '../configuration/configuration';

const specifierOf = (sheet: string): string => (sheet.startsWith('./') || sheet.startsWith('../') ? '../' + sheet.replace(/^\.\//, '') : sheet);

// THE TEXT OF IT, WITHOUT WRITING IT ANYWHERE, so a dev server can serve this module with no file
// for it on disk. The batch below still writes one, because a publish bundles files.
export const assembled = (chosen: Configuration): string => [
    `// GENERATED by assembly/stylesheets.ts on every build — never edited. The sheets .pubconfig names, imported so vite bundles them.`,
    ...chosen.rendering.stylesheets.map(sheet => `import ${JSON.stringify(specifierOf(sheet))};`),
    `export {};`,
    ``,
].join('\n');

export const stylesheets = (binding: string, chosen: Configuration): string => {
    const at = join(binding, 'application', 'stylesheets.ts');
    writeFileSync(at, assembled(chosen), 'utf8');

    return relative(join(binding, '..'), at).split('\\').join('/');
};
