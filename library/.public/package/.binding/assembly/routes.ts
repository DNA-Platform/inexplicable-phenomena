import { writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Table } from '../resolution/addresses';

// WHERE EACH BOOK STANDS. Addressing only: every route reaches its book through the one door the
// assembly wrote, so a page is loaded the same way whoever asks for it.
//
// AND THE SHELF IS PUT UP HERE, NOT IN THE ENTRY. A book mentioned inside another book has to lead
// to that book's PAGE, and only the binder knows where each one was published — so the addresses it
// resolved are handed to $$Book.shelve, which is what turns a pile of separate pages into a library
// somebody can walk around in. Measured 2026-09-15: said in application/main.tsx instead, every
// `<Book>MY Library Log</Book>` in the PRERENDERED markup came out as `href="#my-library-log"` — an
// anchor to an id that is not on the page — because the prerender loads this table and never loads
// the entry. Said here, the shelf is up for whoever imports the table, which is both of them.
export const routes = (binding: string, table: Table): string => {
    const at = join(binding, 'application', 'routes.ts');
    const lines = [
        `// GENERATED by assembly/routes.ts on every build — never edited. Where each book of the library stands.`,
        `import { $$Book, type $Book } from '@dna-platform/public';`,
        `import { books } from './books';`,
        ``,
        `export type Route = { name: string; folder: string; address: string; load: () => Promise<{ book: $Book }> };`,
        ``,
        `export const routes: Route[] = [`,
        ...table.routes.map(route =>
            `    { name: ${JSON.stringify(route.name)}, folder: ${JSON.stringify(route.folder)}, address: ${JSON.stringify(route.address)}, load: books[${JSON.stringify(route.folder)}] },`),
        `];`,
        ``,
        `export const root: Route | undefined = ${table.root ? `routes[${table.routes.indexOf(table.root)}]` : 'undefined'};`,
        ``,
        `// THE LIBRARY IS CONNECTED HERE, BEFORE ANY BOOK IS OPENED. Every page that loads this table`,
        `// has the shelf up, which is what makes a mention of a book lead to that book.`,
        `const base = import.meta.env.BASE_URL.replace(/\\/$/, '');`,
        `$$Book.shelve(routes.map(route => ({ name: route.name, address: \`\${base}\${route.address}\${route.address.endsWith('/') ? '' : '/'}\` })));`,
        ``,
    ];
    writeFileSync(at, lines.join('\n'), 'utf8');

    return relative(join(binding, '..'), at).split(sep).join('/');
};
