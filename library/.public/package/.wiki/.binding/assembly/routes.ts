import { writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Table } from '../resolution/addresses';

export const routes = (binding: string, table: Table): string => {
    const at = join(binding, 'application', 'routes.ts');
    const lines = [
        `// GENERATED by assembly/routes.ts on every build — never edited. The route table, read off the library.`,
        `import type { $Book } from '@dna-platform/public';`,
        ``,
        `export type Route = { name: string; address: string; load: () => Promise<{ book: $Book }> };`,
        ``,
        `export const routes: Route[] = [`,
        ...table.routes.map(route =>
            `    { name: ${JSON.stringify(route.name)}, address: ${JSON.stringify(route.address)}, load: () => import(${JSON.stringify(route.specifier)}) },`),
        `];`,
        ``,
        `export const root: Route | undefined = ${table.root ? `routes[${table.routes.indexOf(table.root)}]` : 'undefined'};`,
        ``,
    ];
    writeFileSync(at, lines.join('\n'), 'utf8');
    return relative(join(binding, '..'), at).split('\\').join('/');
};
