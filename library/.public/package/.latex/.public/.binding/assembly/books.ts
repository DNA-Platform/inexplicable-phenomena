import { writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Table } from '../resolution/addresses';

export const books = (binding: string, table: Table): string => {
    const at = join(binding, 'application', 'books.ts');
    const lines = [
        `// GENERATED by assembly/books.ts on every build — never edited. Every book in the library, by name.`,
        `import type { $Book } from '@dna-platform/public';`,
        ``,
        `export const books: Record<string, () => Promise<{ book: $Book }>> = {`,
        ...table.routes.map(route => `    ${JSON.stringify(route.name)}: () => import(${JSON.stringify(route.specifier)}),`),
        `};`,
        ``,
        `export const named: string[] = Object.keys(books);`,
        ``,
    ];
    writeFileSync(at, lines.join('\n'), 'utf8');
    return relative(join(binding, '..'), at).split('\\').join('/');
};
