import { writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Library } from '../inventory/library';
import { specifierOf } from '../resolution/addresses';

// THE IMPORT OF ALL THE BOOKS — the one door into the library, written at assemble and keyed by
// FOLDER, which is what a book has before anything has read it. A book is reached through here by
// everything: the specification that reads them, the prerender that draws them, and the browser.
// Addressing is a different job and comes later, in routes.ts, because a name is a thing a running
// book answers and cannot exist this early.
export const books = (binding: string, found: Library): string => {
    const at = join(binding, 'application', 'books.ts');
    const lines = [
        `// GENERATED by assembly/books.ts on every build — never edited. Every book in the library, by folder.`,
        `import type { $Book } from '@dna-platform/public';`,
        ``,
        `export const books: Record<string, () => Promise<{ book: $Book }>> = {`,
        ...found.books.map(book => `    ${JSON.stringify(book.folder)}: () => import(${JSON.stringify(specifierOf(binding, book.module))}),`),
        `};`,
        ``,
    ];
    writeFileSync(at, lines.join('\n'), 'utf8');

    return relative(join(binding, '..'), at).split(sep).join('/');
};
